package dev.carcara.kotlinx.locale.codegen

import java.io.File

/**
 * Writes the RGI flag region codes into the conformance suite.
 *
 * The generation-time check in [crossCheckCountryFlags] already proves every
 * country has a flag, but it proves it about the generator. This fixture proves
 * it about the shipped `Country.flagEmoji`, on every target, which is where the
 * surrogate-pair arithmetic actually runs.
 */
fun emitEmojiFlagGolden(outputFile: File, emoji: EmojiData) {
    outputFile.parentFile.mkdirs()
    outputFile.writeText(
        buildString {
            append("// GENERATED by :codegen from Unicode Emoji ${emoji.version}. Do not edit.\n")
            append("// Regenerate with: ./gradlew :codegen:generateLocaleData\n")
            append("package dev.carcara.kotlinx.locale.conformance\n\n")
            append("public const val RGI_EMOJI_VERSION: String = \"${kotlinEscape(emoji.version)}\"\n\n")
            append("/** The region codes UTS #51 lists as RGI flag sequences, sorted. */\n")
            append("public val rgiFlagRegionCodes: Set<String> = setOf(\n")
            for (flag in emoji.flags) {
                append("    \"")
                append(kotlinEscape(flag.regionCode))
                append("\",\n")
            }
            append(")\n")
        },
    )
    println("[codegen] emitted ${emoji.flags.size} RGI flag region codes to $outputFile")
}
