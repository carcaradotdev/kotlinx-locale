package dev.carcara.kotlinx.locale.codegen

import com.ibm.icu.number.NumberFormatter
import com.ibm.icu.util.Currency
import com.ibm.icu.util.ULocale
import java.io.File
import java.math.BigDecimal

/**
 * Goldens for currency output, generated by asking ICU4J to format the same
 * amounts.
 *
 * The currency goldens that already exist compare tables: symbols, display
 * names, separators, the pattern string. Nothing compared what those tables
 * produce once the formatter has run over them, which is a real hole rather than
 * a theoretical one. UTS #35 currency spacing changed 500 outputs across the
 * bundled locales and every existing golden passed unchanged both before and
 * after, because none of them formats anything. The rule had to be checked by
 * hand against a throwaway ICU probe.
 *
 * What this pins is the composition: which pattern was chosen, whether the
 * `alphaNextToNumber` variant applied, where the spacing landed, which spelling
 * of the symbol was substituted, and how the sign and the accounting parentheses
 * wrap all of it. Those interact, and the interaction is where the bugs are.
 *
 * The five widths map one to one onto `CurrencySymbolStyle`, so a golden entry
 * covers every spelling this library can write. `FULL_NAME` is deliberately
 * absent: it is ICU's plural currency name, and this library does not carry the
 * plural display names yet. It belongs here on the day it does.
 */

/**
 * The locales the currency output goldens cover.
 *
 * The shared golden set, plus locales chosen for what they do to the boundary
 * between the currency and the digits. `af en_ZA si ta dz kl es_VE es_PA` are
 * where the currency spacing rule actually fires, either because the symbol ends
 * in a letter or a full stop or because the locale has no symbol at all and
 * falls back to the ISO code. `da hu` write the currency after the number, which
 * is the other side of the same rule.
 */
val ICU_CURRENCY_FORMAT_GOLDEN_LOCALES: List<String> = (
    ICU_GOLDEN_LOCALES + listOf(
        "af", "en_ZA", "si", "ta", "dz", "kl", "es_VE", "es_PA", "da", "hu",
        "de_CH", "es_419", "nb", "is", "sq", "lt", "lv", "et", "sk", "sl",
    )
    ).distinct()

/**
 * The currencies every locale is asked about.
 *
 * Picked for fraction digits and for symbol shape rather than for importance.
 * `JPY` has none and `BHD` has three, `HUF` prints fewer than ISO defines, and
 * `CHF` rounds cash to 0.05. `XCG` writes `Cg.`, `TRY` is the one currency with
 * all three alternative spellings, and `TWD` carries CLDR's only formal symbol.
 * `AED` has no symbol in most locales and so exercises the ISO-code fallback,
 * which is the case the spacing rule fires on most often.
 */
val ICU_CURRENCY_FORMAT_GOLDEN_CODES: List<String> = listOf(
    "USD", "EUR", "JPY", "BHD", "HUF", "CHF", "XCG", "TRY", "TWD", "AED",
    "DKK", "LKR", "BRL", "ZAR", "SEK", "PLN",
)

/**
 * The amounts, as ISO minor units, the way this library carries money.
 *
 * Zero and one are here because a locale's pattern can treat them differently,
 * the negatives because the sign and the accounting parentheses wrap the
 * currency rather than the number, and 123456 because it is large enough to
 * group in every locale.
 */
val ICU_CURRENCY_FORMAT_GOLDEN_MINOR_UNITS: List<Long> = listOf(0, 1, 100, 123456, -1, -123456)

/** One width: our style name, and the ICU width that means the same thing. */
class IcuCurrencyWidth(val style: String, val width: NumberFormatter.UnitWidth)

/**
 * The widths, named for the [CurrencySymbolStyle] entry each one answers.
 *
 * ICU exposes exactly these five for a currency, which is why the enum has five
 * members rather than a symbol flag and a separate width.
 */
val ICU_CURRENCY_FORMAT_GOLDEN_WIDTHS: List<IcuCurrencyWidth> = listOf(
    IcuCurrencyWidth("SYMBOL", NumberFormatter.UnitWidth.SHORT),
    IcuCurrencyWidth("NARROW_SYMBOL", NumberFormatter.UnitWidth.NARROW),
    IcuCurrencyWidth("VARIANT_SYMBOL", NumberFormatter.UnitWidth.VARIANT),
    IcuCurrencyWidth("FORMAL_SYMBOL", NumberFormatter.UnitWidth.FORMAL),
    IcuCurrencyWidth("CODE", NumberFormatter.UnitWidth.ISO_CODE),
)

/**
 * One locale's answers, plus the symbols they were produced from.
 *
 * The symbols travel with the output for the same reason the number goldens
 * check ICU's tables before trusting its answers. ICU 78.3 is built from a CLDR
 * snapshot near but not identical to `release-48-2`, so a symbol that moved
 * between the two would report a data difference as a formatting bug. Recording
 * what ICU formatted from lets the test skip exactly those pairs and assert on
 * the rest, rather than dropping a whole locale or, worse, failing for a reason
 * that has nothing to do with the code.
 */
class IcuCurrencyFormatGoldenEntry(
    val tag: String,
    /** `code|STYLE` to the symbol ICU used. */
    val symbols: Map<String, String>,
    /** `code|STYLE` to answers, positional against [ICU_CURRENCY_FORMAT_GOLDEN_MINOR_UNITS]. */
    val answers: Map<String, List<String>>,
)

/** ISO minor units to the decimal string ICU takes, at the currency's own scale. */
private fun minorUnitsToDecimal(minorUnits: Long, digits: Int): BigDecimal = BigDecimal.valueOf(minorUnits, digits)

/**
 * [isoMinorUnits] is the ISO 4217 scale per code, which is not ICU's.
 *
 * `Currency.getDefaultFractionDigits` answers CLDR's formatting digits, and the
 * two differ for exactly the currencies this fixture most wants to cover: the
 * forint has two ISO decimals and CLDR prints none. Scaling the amount by ICU's
 * answer would hand ICU one forint where this library means one filler, and the
 * golden would then encode a unit mismatch as a formatting difference.
 */
fun extractIcuCurrencyFormatGolden(isoMinorUnits: Map<String, Int>): List<IcuCurrencyFormatGoldenEntry> {
    // Same reason as the other ICU goldens: ICU resolves a locale it does not
    // carry against the default one, so an unpinned JVM would answer in whatever
    // the build machine happened to be set to.
    ULocale.setDefault(ULocale.ROOT)
    java.util.Locale.setDefault(java.util.Locale.ROOT)

    val available = ULocale.getAvailableLocales().mapTo(HashSet()) { it.toLanguageTag() }
    val missing = ArrayList<String>()
    val entries = ArrayList<IcuCurrencyFormatGoldenEntry>()

    for (cldrId in ICU_CURRENCY_FORMAT_GOLDEN_LOCALES) {
        val tag = canonicalTag(cldrId)
        if (tag !in available) {
            missing.add(tag)
            continue
        }
        val locale = ULocale.forLanguageTag(tag)
        val symbols = LinkedHashMap<String, String>()
        val answers = LinkedHashMap<String, List<String>>()

        for (code in ICU_CURRENCY_FORMAT_GOLDEN_CODES) {
            val currency = Currency.getInstance(code) ?: continue
            val digits = isoMinorUnits[code]?.takeIf { it >= 0 } ?: continue
            for (width in ICU_CURRENCY_FORMAT_GOLDEN_WIDTHS) {
                val key = "$code|${width.style}"
                symbols[key] = currency.getName(locale, currencyNameStyle(width.style), null) ?: code
                val formatter = NumberFormatter.withLocale(locale).unit(currency).unitWidth(width.width)
                answers[key] = ICU_CURRENCY_FORMAT_GOLDEN_MINOR_UNITS.map { minorUnits ->
                    formatter.format(minorUnitsToDecimal(minorUnits, digits)).toString()
                }
            }
        }
        entries.add(IcuCurrencyFormatGoldenEntry(tag, symbols, answers))
    }

    val cells = entries.sumOf { it.answers.size } * ICU_CURRENCY_FORMAT_GOLDEN_MINOR_UNITS.size
    println(
        "[codegen] currency format goldens cover ${entries.size} locales " +
            "(${ICU_CURRENCY_FORMAT_GOLDEN_CODES.size} currencies x ${ICU_CURRENCY_FORMAT_GOLDEN_WIDTHS.size} widths " +
            "x ${ICU_CURRENCY_FORMAT_GOLDEN_MINOR_UNITS.size} amounts = $cells strings); " +
            "${missing.size} are absent from ICU4J",
    )
    check(entries.size >= 30) { "expected the currency format goldens to cover at least 30 locales, got ${entries.size}" }
    return entries
}

/** The `Currency` name style constant behind each of our style names. */
private fun currencyNameStyle(style: String): Int = when (style) {
    "NARROW_SYMBOL" -> Currency.NARROW_SYMBOL_NAME
    "FORMAL_SYMBOL" -> Currency.FORMAL_SYMBOL_NAME
    "VARIANT_SYMBOL" -> Currency.VARIANT_SYMBOL_NAME
    "CODE" -> Currency.SYMBOL_NAME
    else -> Currency.SYMBOL_NAME
}

fun emitIcuCurrencyFormatGolden(outputFile: File, icuTag: String, entries: List<IcuCurrencyFormatGoldenEntry>) {
    outputFile.parentFile.mkdirs()
    outputFile.writeText(
        buildString {
            append(LICENSE_HEADER + "// GENERATED by :codegen from ICU $icuTag. Do not edit.\n")
            append("// Regenerate with: ./gradlew :codegen:generateLocaleData\n")
            append("package dev.carcara.kotlinx.locale.conformance\n\n")
            append("public const val ICU_CURRENCY_FORMAT_GOLDEN_VERSION: String = \"${kotlinEscape(icuTag)}\"\n\n")
            append("/** The amounts every record answers, in ISO minor units, in order. */\n")
            append("public val icuCurrencyFormatGoldenMinorUnits: List<Long> = listOf(\n")
            for (value in ICU_CURRENCY_FORMAT_GOLDEN_MINOR_UNITS) append("    ${value}L,\n")
            append(")\n\n")
            append("/**\n")
            append(" * One locale's answers: `code|STYLE` to the symbol ICU used and the strings\n")
            append(" * it wrote.\n")
            append(" *\n")
            append(" * Both are held encoded and split on first use rather than written as map\n")
            append(" * literals. Twenty four thousand strings across eight thousand map entries\n")
            append(" * put the static initializer over the JVM's 64 KB method limit, and the\n")
            append(" * number goldens encode their rows for the same reason.\n")
            append(" */\n")
            append("public class IcuCurrencyFormatGolden(private val encodedSymbols: String, private val encodedAnswers: String) {\n\n")
            append("    public val symbols: Map<String, String> by lazy {\n")
            append("        encodedSymbols.split('\\u001E').associate {\n")
            append("            val split = it.indexOf('\\u001D')\n")
            append("            it.substring(0, split) to it.substring(split + 1)\n")
            append("        }\n")
            append("    }\n\n")
            append("    public val answers: Map<String, List<String>> by lazy {\n")
            append("        encodedAnswers.split('\\u001E').associate {\n")
            append("            val split = it.indexOf('\\u001D')\n")
            append("            it.substring(0, split) to it.substring(split + 1).split('\\u001F')\n")
            append("        }\n")
            append("    }\n")
            append("}\n\n")
            append("/** Locale tag to its record. */\n")
            append("public val icuCurrencyFormatGoldenData: Map<String, IcuCurrencyFormatGolden> = buildMap(${entries.size}) {\n")
            for (entry in entries.sortedBy { it.tag }) {
                val symbols = entry.symbols.entries.joinToString(LIST_SEPARATOR) { (key, value) -> key + KEY_SEPARATOR + value }
                val answers = entry.answers.entries.joinToString(LIST_SEPARATOR) { (key, values) ->
                    key + KEY_SEPARATOR + values.joinToString(FIELD_SEPARATOR)
                }
                append("    put(\n")
                append("        \"${kotlinEscape(entry.tag)}\",\n")
                append("        IcuCurrencyFormatGolden(\n")
                append("            \"${kotlinEscape(symbols)}\",\n")
                append("            \"${kotlinEscape(answers)}\",\n")
                append("        ),\n")
                append("    )\n")
            }
            append("}\n")
        },
    )
    println("[codegen] emitted ${entries.size} ICU currency format golden entries to $outputFile")
}
