package dev.carcara.kotlinx.locale.codegen

import java.io.File

/**
 * CLDR's own datetime cases, as a second opinion on the skeleton matcher.
 *
 * The ICU4J goldens are the specification the matcher is held to, but they and
 * the matcher were both written against ICU's reading of UTS #35. These cases
 * come from CLDR itself and check formatted output rather than patterns, so they
 * exercise the renderer too and would catch a matcher and a golden that agreed
 * with each other and with nothing else.
 *
 * Be clear about how little of the file applies. Of its 312 cases, 240 carry a
 * `classicalSkeleton`; 60 of those are gregorian, and dropping the ones whose
 * skeleton names a time zone leaves 36, all of them `en`, over ten skeletons.
 * That is a smoke test, not coverage.
 */
class CldrDateTimeCase(val locale: String, val skeleton: String, val dateTime: String, val expected: String)

private val ZONE_LETTERS = setOf('v', 'z', 'O', 'V', 'Z', 'X', 'x')

fun extractCldrDateTimeCases(cldrDir: File): List<CldrDateTimeCase> {
    val file = cldrDir.resolve("common/testData/datetime/datetime.json")
    if (!file.exists()) {
        println("[codegen] WARNING: $file not found, skipping the CLDR datetime cases")
        return emptyList()
    }

    val cases = ArrayList<CldrDateTimeCase>()
    var skipped = 0
    for (entry in parseFlatJsonObjects(file.readText())) {
        val skeleton = entry["classicalSkeleton"] ?: continue
        val expected = entry["expected"] ?: continue
        val input = entry["input"] ?: continue
        if (entry["calendar"] != "gregorian" || entry.containsKey("zoneStyle") || skeleton.any { it in ZONE_LETTERS }) {
            skipped++
            continue
        }
        // "2024-07-01T08:50:07Z[Etc/GMT]"; every case is at Etc/GMT, so the
        // local time is what precedes the zone.
        cases.add(
            CldrDateTimeCase(
                locale = entry["locale"] ?: "en",
                skeleton = skeleton,
                dateTime = input.substringBefore('Z'),
                expected = expected,
            ),
        )
    }
    println("[codegen] ${cases.size} CLDR datetime cases are in scope ($skipped are not gregorian or name a zone)")
    return cases
}

fun emitCldrDateTimeCases(outputFile: File, cldrTag: String, cases: List<CldrDateTimeCase>) {
    outputFile.parentFile.mkdirs()
    outputFile.writeText(
        buildString {
            append("// GENERATED by :codegen from CLDR $cldrTag. Do not edit.\n")
            append("// Regenerate with: ./gradlew :codegen:generateLocaleData\n")
            append("package dev.carcara.kotlinx.locale.conformance\n\n")
            append("/** One case from CLDR's own `common/testData/datetime/datetime.json`. */\n")
            append("public class CldrDateTimeCase(\n")
            append("    public val locale: String,\n")
            append("    public val skeleton: String,\n")
            append("    /** ISO 8601 local date-time; every case in scope is at Etc/GMT. */\n")
            append("    public val dateTime: String,\n")
            append("    public val expected: String,\n")
            append(")\n\n")
            append("public val cldrDateTimeCases: List<CldrDateTimeCase> = listOf(\n")
            for (case in cases) {
                append("    CldrDateTimeCase(\"")
                append(kotlinEscape(case.locale))
                append("\", \"")
                append(kotlinEscape(case.skeleton))
                append("\", \"")
                append(kotlinEscape(case.dateTime))
                append("\", \"")
                append(kotlinEscape(case.expected))
                append("\"),\n")
            }
            append(")\n")
        },
    )
    println("[codegen] emitted ${cases.size} CLDR datetime cases to $outputFile")
}

/**
 * A JSON reader for exactly the shape this file has: an array of objects whose
 * values are all strings.
 *
 * Small enough to be worth writing rather than taking a dependency for, and
 * deliberately unforgiving — it fails loudly rather than silently reading half
 * a file, so a change in the upstream shape surfaces at generation time.
 */
private fun parseFlatJsonObjects(text: String): List<Map<String, String>> {
    val objects = ArrayList<Map<String, String>>()
    var i = 0

    fun skipWhitespace() {
        while (i < text.length && text[i].isWhitespace()) i++
    }

    fun readString(): String {
        require(text[i] == '"') { "expected a string at offset $i" }
        i++
        val sb = StringBuilder()
        while (text[i] != '"') {
            if (text[i] == '\\') {
                i++
                when (val escape = text[i]) {
                    'n' -> sb.append('\n')
                    't' -> sb.append('\t')
                    'r' -> sb.append('\r')
                    'b' -> sb.append('\b')
                    'f' -> sb.append('')
                    'u' -> {
                        sb.append(text.substring(i + 1, i + 5).toInt(16).toChar())
                        i += 4
                    }
                    else -> sb.append(escape)
                }
            } else {
                sb.append(text[i])
            }
            i++
        }
        i++
        return sb.toString()
    }

    skipWhitespace()
    require(text[i] == '[') { "expected a JSON array" }
    i++
    while (true) {
        skipWhitespace()
        if (text[i] == ']') break
        if (text[i] == ',') {
            i++
            continue
        }
        require(text[i] == '{') { "expected an object at offset $i" }
        i++
        val entry = LinkedHashMap<String, String>()
        while (true) {
            skipWhitespace()
            if (text[i] == '}') {
                i++
                break
            }
            if (text[i] == ',') {
                i++
                continue
            }
            val key = readString()
            skipWhitespace()
            require(text[i] == ':') { "expected ':' at offset $i" }
            i++
            skipWhitespace()
            entry[key] = readString()
        }
        objects.add(entry)
    }
    return objects
}
