package dev.carcara.kotlinx.locale.codegen

import java.io.File

private const val COUNTRY_PACKAGE = "dev.carcara.kotlinx.locale.country"

/**
 * Emits the Country enum into the -types layer: the entry list and nothing
 * else. Every behaviour is an extension declared in -core or in an
 * implementation module, which is what keeps this emitter writing data only
 * and lets the Gradle plugin narrow the entry set without copying logic.
 */
fun emitCountryEnum(outputFile: File, cldrTag: String, countries: List<CountryInfo>) {
    outputFile.parentFile.mkdirs()
    val entries = buildString {
        for (country in countries) {
            append("    /** ")
            append(country.englishName)
            append(" */\n    ")
            append(country.alpha2)
            append("(\"")
            append(country.alpha3)
            append("\", ")
            append(country.numeric)
            append("),\n")
        }
    }
    outputFile.writeText(
        """
        |// GENERATED by :codegen from CLDR $cldrTag. Do not edit.
        |// Regenerate with: ./gradlew :codegen:generateLocaleData
        |package $COUNTRY_PACKAGE
        |
        |/**
        | * The countries of ISO 3166-1, keyed by alpha-2 code.
        | *
        | * Each entry carries only the codes ISO assigns it. Everything else is an
        | * extension: `alpha2` and the `for*` lookups come from
        | * `kotlinx-locale-country-core`, and `displayName` from whichever
        | * implementation module you put on the classpath.
        | */
        |public enum class Country(
        |    /** The ISO 3166-1 alpha-3 code, e.g. `USA`. */
        |    public val alpha3: String,
        |    /** The ISO 3166-1 numeric code, e.g. 840. */
        |    public val numericCode: Int,
        |) {
        |$entries    ;
        |
        |    public companion object
        |}
        |
        """.trimMargin(),
    )
    println("[codegen] emitted ${countries.size} countries to $outputFile")
}

/**
 * Sparse per-locale country-name payloads: the parent tag, then only the names
 * this locale's own file declares. The runtime walks the parent chain.
 */
fun buildCountryNamePayloads(flattener: Flattener, extras: ExtrasResolver): Map<String, String> {
    val payloads = LinkedHashMap<String, String>()
    for (id in listOf("root") + flattener.localeIds) {
        val partial = extras.partial(id)
        val parentTag = flattener.dataChain(id).getOrNull(1)?.let(::canonicalTag).orEmpty()
        val entries = partial.territoryNames.entries
            .sortedBy { it.key }
            .joinToString(LIST_SEPARATOR) { (code, name) -> code + KEY_SEPARATOR + name }
        payloads[canonicalTag(id)] = parentTag + FIELD_SEPARATOR + entries
    }
    return payloads
}
