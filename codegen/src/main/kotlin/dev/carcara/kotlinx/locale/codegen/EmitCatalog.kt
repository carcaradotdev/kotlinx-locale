package dev.carcara.kotlinx.locale.codegen

import java.io.File

private const val CATALOG_PACKAGE = "dev.carcara.kotlinx.locale.catalog"

/**
 * CLDR macroregion codes that appear in locale ids. They are digits, so they
 * cannot be Kotlin identifiers, and backticking them would produce JVM field
 * names Java callers cannot reference. CLDR's own English names instead.
 *
 * Codegen fails rather than guessing if CLDR grows one that is not listed.
 */
private val MACROREGION_NAMES = mapOf(
    "001" to "WORLD",
    "150" to "EUROPE",
    "419" to "LATIN_AMERICA",
)

/**
 * Emits the locale catalog into the -types layer: one enum per language,
 * implementing `LocaleRef`, with a member per locale id that language covers.
 *
 * The nesting follows the *identifier* structure, not the CLDR parent chain.
 * Those differ — `en-150`'s parent is `en-001` and `zh-Hant-MO`'s is
 * `zh-Hant-HK` — and the parent chain is runtime data that belongs to the
 * implementation modules, where it already lives.
 *
 * Two levels, so a reference is always `Language.Rest`: only 33 of the 322
 * languages carry a script, and a third level would pay for those in every
 * other reference.
 */
fun emitLocaleCatalog(outputDir: File, cldrTag: String, localeIds: List<String>) {
    outputDir.mkdirs()
    outputDir.listFiles { f: File -> f.extension == "kt" }?.forEach(File::delete)

    val idsByLanguage = LinkedHashMap<String, MutableList<String>>()
    for (id in localeIds.sorted()) {
        idsByLanguage.getOrPut(id.substringBefore('_')) { ArrayList() }.add(id)
    }

    for ((language, ids) in idsByLanguage) {
        val className = language.replaceFirstChar(Char::uppercaseChar)
        val members = LinkedHashMap<String, String>()
        for (id in ids) {
            val member = memberNameFor(language, id)
            val clash = members.put(member, canonicalTag(id))
            check(clash == null) { "$language: '$member' names both $clash and ${canonicalTag(id)}" }
        }
        outputDir.resolve("$className.kt").writeText(
            buildString {
                append("// GENERATED by :codegen from CLDR ")
                append(cldrTag)
                append(". Do not edit.\n")
                append("// Regenerate with: ./gradlew :codegen:generateLocaleData\n")
                append("package ")
                append(CATALOG_PACKAGE)
                append("\n\nimport dev.carcara.kotlinx.locale.LocaleRef\n")
                append("\n/** The CLDR locales whose language subtag is `")
                append(language)
                append("`. */\n")
                append("public enum class ")
                append(className)
                append("(override val tag: String) : LocaleRef {\n")
                for ((member, tag) in members) {
                    append("    ")
                    append(member)
                    append("(\"")
                    append(kotlinEscape(tag))
                    append("\"),\n")
                }
                append("    ;\n}\n")
            },
        )
    }

    println("[codegen] emitted ${idsByLanguage.size} language catalogs (${localeIds.size} locales) to $outputDir")
}

/** `pt` -> `BASE`, `pt_BR` -> `BR`, `zh_Hans_CN` -> `HANS_CN`, `es_419` -> `LATIN_AMERICA`. */
private fun memberNameFor(language: String, id: String): String {
    val rest = id.removePrefix(language).removePrefix("_")
    if (rest.isEmpty()) return "BASE"
    return rest.split('_').joinToString("_") { part ->
        if (part.first().isDigit()) {
            MACROREGION_NAMES[part]
                ?: error("No identifier name for region '$part' in locale id '$id'; add it to MACROREGION_NAMES")
        } else {
            part.uppercase()
        }
    }
}
