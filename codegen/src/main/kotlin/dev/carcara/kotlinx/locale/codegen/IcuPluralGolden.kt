package dev.carcara.kotlinx.locale.codegen

import com.ibm.icu.text.PluralRules
import com.ibm.icu.util.ULocale
import java.io.File
import java.math.BigDecimal

/**
 * Goldens for plural selection, asked of ICU's own `PluralRules`.
 *
 * The second of two independent fixtures over the same evaluator. The first is
 * CLDR's `@integer` and `@decimal` sample lists, which are normative and come
 * free with parsing `plurals.xml`; this one is ICU answering the same questions
 * from its own compiled copy of the rules.
 *
 * Independent is the point. The sample lists say what CLDR intended and are
 * parsed by the same code that parses the rules, so a misreading of the file
 * format could in principle satisfy both. ICU never sees this repository's
 * parser.
 *
 * The values are chosen for the operands rather than for coverage. Integers
 * reach `n` and `i` with `v` and `f` at zero. The decimals carry explicit
 * trailing zeros, because `1.0` and `1` are the same quantity and different
 * categories in Czech, and `v`, `w`, `f` and `t` are what tells them apart.
 */

/** Integers every locale is asked about, dense at the bottom where the rules are. */
private val PLURAL_GOLDEN_INTEGERS: List<Long> = ((0L..30L) + (31L..210L step 7) + listOf(1000L, 1001L, 10101L)).distinct()

/**
 * Decimals written as text, so the visible fraction digits survive.
 *
 * Parsed rather than computed for the same reason the number goldens are: the
 * count of digits is data, and a double would lose it before ICU saw it.
 */
private val PLURAL_GOLDEN_DECIMALS: List<String> = listOf(
    "0.0", "0.00", "0.1", "0.5", "1.0", "1.00", "1.1", "1.5", "1.9",
    "2.0", "2.5", "3.0", "3.5", "5.0", "10.0", "11.0", "1.03", "1.30",
    "100.0", "101.0", "1.000", "2.07", "20.0", "21.0",
)

class IcuPluralGoldenEntry(
    val tag: String,
    /** Positional against the integers, then the decimals; cardinal then ordinal. */
    val cardinal: List<String>,
    val ordinal: List<String>,
)

fun extractIcuPluralGolden(pluralLocales: Set<String>): List<IcuPluralGoldenEntry> {
    ULocale.setDefault(ULocale.ROOT)
    java.util.Locale.setDefault(java.util.Locale.ROOT)

    val available = ULocale.getAvailableLocales().mapTo(HashSet()) { it.toLanguageTag() }
    val entries = ArrayList<IcuPluralGoldenEntry>()
    var missing = 0

    // Every locale ICU and this build both carry, rather than a sample: plural
    // rules are a pure function of the value, so the whole matrix is cheap and
    // a locale left out is a locale nothing checks.
    for (tag in pluralLocales.sorted()) {
        if (tag !in available) {
            missing++
            continue
        }
        val locale = ULocale.forLanguageTag(tag)
        val cardinal = PluralRules.forLocale(locale, PluralRules.PluralType.CARDINAL)
        val ordinal = PluralRules.forLocale(locale, PluralRules.PluralType.ORDINAL)
        entries.add(
            IcuPluralGoldenEntry(
                tag = tag,
                cardinal = selections(cardinal),
                ordinal = selections(ordinal),
            ),
        )
    }
    println("[codegen] plural goldens cover ${entries.size} locales; $missing are absent from ICU4J")
    check(entries.size > 100) { "expected the plural goldens to cover most locales, got ${entries.size}" }
    return entries
}

private fun selections(rules: PluralRules): List<String> = PLURAL_GOLDEN_INTEGERS.map { rules.select(it.toDouble()) } +
    PLURAL_GOLDEN_DECIMALS.map { rules.select(PluralRules.FixedDecimal(BigDecimal(it).toDouble(), it.substringAfter('.').length)) }

fun emitIcuPluralGolden(outputFile: File, icuTag: String, entries: List<IcuPluralGoldenEntry>) {
    outputFile.parentFile.mkdirs()
    outputFile.writeText(
        buildString {
            append(LICENSE_HEADER + "// GENERATED by :codegen from ICU $icuTag. Do not edit.\n")
            append("// Regenerate with: ./gradlew :codegen:generateLocaleData\n")
            append("package dev.carcara.kotlinx.locale.conformance\n\n")
            append("public const val ICU_PLURAL_GOLDEN_VERSION: String = \"${kotlinEscape(icuTag)}\"\n\n")
            append("/** The integers every record answers, in order, ahead of the decimals. */\n")
            append("public val icuPluralGoldenIntegers: List<Long> = listOf(\n")
            for (value in PLURAL_GOLDEN_INTEGERS) append("    ${value}L,\n")
            append(")\n\n")
            append("/** The decimals every record answers, written as the digit count matters. */\n")
            append("public val icuPluralGoldenDecimals: List<String> = listOf(\n")
            for (value in PLURAL_GOLDEN_DECIMALS) append("    \"${kotlinEscape(value)}\",\n")
            append(")\n\n")
            append("/** Locale tag to its cardinal categories, then its ordinal ones. */\n")
            append("public val icuPluralGoldenData: Map<String, Pair<List<String>, List<String>>> =\n")
            append("    buildMap(${entries.size}) {\n")
            for (entry in entries) {
                append("        put(\n")
                append("            \"${kotlinEscape(entry.tag)}\",\n")
                append("            \"${kotlinEscape(entry.cardinal.joinToString(LIST_SEPARATOR))}\".split('\\u001E') to\n")
                append("                \"${kotlinEscape(entry.ordinal.joinToString(LIST_SEPARATOR))}\".split('\\u001E'),\n")
                append("        )\n")
            }
            append("    }\n")
        },
    )
    println("[codegen] emitted ${entries.size} ICU plural golden locales to $outputFile")
}
