package dev.carcara.kotlinx.locale.codegen

import java.io.File

/**
 * Writes CLDR's own plural samples into the conformance suite.
 *
 * These are the strongest fixture in the number domain and they cost nothing to
 * produce: `plurals.xml` writes an `@integer` and `@decimal` list under every
 * rule saying which values fall into it, so asserting that the shipped evaluator
 * agrees is CLDR checking this library with CLDR's own data, independently of
 * ICU, on every target.
 *
 * The samples are stored as text rather than as numbers because the fraction
 * digits matter: `1.0` and `1` are different samples of different categories in
 * Czech, and parsing them into a double would lose exactly the operand the rule
 * reads.
 */
fun emitCldrPluralSamples(outputFile: File, cldrTag: String, samples: List<PluralSample>) {
    // One representative locale per rule set is enough: the samples belong to the
    // rule, and every locale sharing it shares the answer.
    val byLocale = LinkedHashMap<String, MutableList<PluralSample>>()
    for (sample in samples) {
        val locale = sample.locales.split(' ').first { it.isNotEmpty() }
        byLocale.getOrPut(locale) { ArrayList() }.add(sample)
    }

    outputFile.parentFile.mkdirs()
    outputFile.writeText(
        buildString {
            append(LICENSE_HEADER + "// GENERATED by :codegen from CLDR $cldrTag. Do not edit.\n")
            append("// Regenerate with: ./gradlew :codegen:generateLocaleData\n")
            append("package ${packageOf(outputFile)}\n\n")
            append("/** One value CLDR says falls into one plural category, for one locale. */\n")
            append("public class CldrPluralSample(\n")
            append("    public val tag: String,\n")
            append("    public val category: String,\n")
            append("    /** As written in CLDR, so the visible fraction digits survive. */\n")
            append("    public val value: String,\n")
            append("    public val isOrdinal: Boolean,\n")
            append(")\n\n")
            append("public val cldrPluralSamples: List<CldrPluralSample> = listOf(\n")
            for ((locale, entries) in byLocale) {
                for (sample in entries) {
                    append("    CldrPluralSample(\"")
                    append(kotlinEscape(canonicalTag(locale)))
                    append("\", \"")
                    append(kotlinEscape(sample.category))
                    append("\", \"")
                    append(kotlinEscape(sample.value))
                    append("\", ")
                    append(sample.isOrdinal)
                    append("),\n")
                }
            }
            append(")\n")
        },
    )
    println("[codegen] emitted ${samples.size} CLDR plural samples to $outputFile")
}
