import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

/**
 * Collects what every size probe measured into one table, and writes it as the
 * document that ships in `docs/`.
 *
 * The numbers are the point of the whole split, so they are worth reading in one
 * place rather than scattered through the log of whichever probes happened to
 * re-run. They were also worth copying into the prose by hand exactly once:
 * generating the document is what stops four tables from drifting apart.
 */
@DisableCachingByDefault(because = "it aggregates other tasks' outputs and is cheap next to the probe builds it reads")
abstract class SizeReport : DefaultTask() {

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val reports: ConfigurableFileCollection

    /**
     * How many probes the build declares.
     *
     * Checked rather than trusted: a probe added to `gradle/size-probes.txt` but
     * missing from the report would otherwise just be a row nobody notices is
     * absent.
     */
    @get:Input
    abstract val expectedProbes: Property<Int>

    /** The generated document. `updateSizeDoc` is what copies it into `docs/`. */
    @get:OutputFile
    abstract val document: RegularFileProperty

    @TaskAction
    fun report() {
        val rows = reports.files
            .filter { it.isFile }
            .map { it.readText().trim().split('\t') }
            .filter { it.size == 4 }
            .map { Row(it[0], it[1].toLong(), it[2].toLong(), it[3].toLong()) }
            .sortedBy { it.gzip }

        val expected = expectedProbes.get()
        check(rows.size == expected) {
            "expected $expected size probes but got ${rows.size}; a probe in gradle/size-probes.txt " +
                "is not offering a report, or its checkSize task did not run"
        }

        logger.lifecycle(budgetTable(rows))
        document.get().asFile.apply {
            parentFile.mkdirs()
            writeText(document(rows))
        }
    }

    private fun budgetTable(rows: List<Row>): String = buildString {
        appendLine()
        appendLine("| scenario | gzip | raw | budget | headroom |")
        appendLine("| --- | ---: | ---: | ---: | ---: |")
        for (row in rows) {
            appendLine(
                "| ${row.label} | ${kb(row.gzip)} | ${kb(row.raw)} | ${kb(row.budget)} | " +
                    "${kb(row.budget - row.gzip)} |",
            )
        }
    }

    /**
     * The comparison the platform layer exists to make, derived rather than
     * written down: every `-platform` probe against the CLDR probe it mirrors
     * call for call.
     */
    private fun pairings(rows: List<Row>): List<Pair<Row, Row>> {
        val byLabel = rows.associateBy { it.label }
        return rows
            .filter { it.label.endsWith(PLATFORM_SUFFIX) }
            .mapNotNull { platform ->
                val stem = platform.label.removeSuffix(PLATFORM_SUFFIX)
                val counterpart = byLabel[if (stem == EVERYTHING) EVERYTHING else "$stem-full"]
                counterpart?.let { platform to it }
            }
            .sortedBy { it.second.gzip }
    }

    private fun document(rows: List<Row>): String = buildString {
        appendLine("# Size")
        appendLine()
        appendLine("Generated by `./gradlew updateSizeDoc`. Do not edit.")
        appendLine()
        appendLine("Gzip over the minified Kotlin/JS bundle, which is what a CDN would serve. Kotlin/JS")
        appendLine("is the only target with dead code elimination, so it is the only one where \"what")
        appendLine("does this artifact cost\" has an answer a build can check. The same module")
        appendLine("boundaries buy the saving on JVM, Android and Native, where nothing is eliminated")
        appendLine("and the dependency block is the only lever there is.")
        appendLine()
        appendLine("Each row is one Kotlin/JS application under `tools/`, built from a real dependency")
        appendLine("set. The budget is a ceiling `checkSize` enforces, not a target.")
        appendLine()
        append(budgetTable(rows).trimStart('\n'))

        val pairs = pairings(rows)
        if (pairs.isNotEmpty()) {
            appendLine()
            appendLine("## What the platform layer costs")
            appendLine()
            appendLine("The `-platform` probes make the same calls as the CLDR probes they mirror,")
            appendLine("resolved against the host instead of against bundled tables, so the difference")
            appendLine("between the two columns is the data and nothing else.")
            appendLine()
            appendLine("| domain | platform | CLDR | what survives | saved |")
            appendLine("| --- | ---: | ---: | ---: | ---: |")
            for ((platform, cldr) in pairs) {
                // Named for the domain rather than the probe, which also keeps this
                // table's rows out of the ones CheckSizeDoc reads as measurements.
                val stem = platform.label.removeSuffix(PLATFORM_SUFFIX)
                    .let { if (it == EVERYTHING) "all three" else it }
                appendLine(
                    "| $stem | ${kb(platform.gzip)} | ${kb(cldr.gzip)} | " +
                        "${percent(platform.gzip, cldr.gzip)} | ${kb(cldr.gzip - platform.gzip)} |",
                )
            }
        }
    }

    private data class Row(val label: String, val gzip: Long, val raw: Long, val budget: Long)

    private fun percent(part: Long, whole: Long): String {
        if (whole == 0L) return "n/a"
        // Rounded, unlike the KB figures: those are truncated to match what the
        // budget failures print, and a share of a total deserves the nearer value.
        val tenths = (part * 1000 + whole / 2) / whole
        return "${tenths / 10}.${tenths % 10}%"
    }

    private fun kb(bytes: Long): String {
        val tenths = bytes * 10 / 1024
        return "${tenths / 10}.${tenths % 10} KB"
    }

    private companion object {
        const val PLATFORM_SUFFIX = "-platform"

        /** The one scenario whose CLDR counterpart is not named `-full`. */
        const val EVERYTHING = "everything"
    }
}
