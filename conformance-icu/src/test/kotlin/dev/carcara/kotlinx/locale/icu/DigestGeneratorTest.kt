/**
 * Writes the per-locale digests the other twenty-four targets are held to.
 *
 * This is a generator that lives in a test source set, which is unusual and
 * deliberate: the digests are of *this library's* output, not of ICU's, so the
 * thing that produces them has to be the library itself running somewhere. The
 * JVM is the only target that can also write files.
 *
 * `./gradlew :conformance-icu:updateDigests` rewrites the fixtures. The normal
 * test run only checks that the committed ones still describe this JVM, which is
 * what stops them going stale without anyone noticing.
 *
 * See `Digest` in the conformance suite for why the scope is these domains and
 * not the name tables.
 */
val DigestGeneratorTest by matrixSuite {

    val tags = CldrNumber.supportedLocales.map { it.toLanguageTag() }.sorted()

    test("the digest set covers the whole shipped catalogue") {
        assertTrue(tags.size > 1000, "only ${tags.size} locales carry number data, which is a collapse")
    }

    test("number digests are current") {
        settleDigests("number", tags) { tag -> numberSerialization(Locale.forLanguageTag(tag)) }
    }

    test("currency format digests are current") {
        settleDigests("currency-format", tags) { tag -> currencySerialization(Locale.forLanguageTag(tag)) }
    }

    test("plural digests are current") {
        settleDigests("plural", tags) { tag -> pluralSerialization(Locale.forLanguageTag(tag)) }
    }
}

/** The values whose formatting exercises grouping, rounding and compact selection. */
private val NUMBER_VALUES = listOf(
    "0", "1", "-1", "0.5", "1.5", "2.5", "-2.5", "1234.5678", "999999", "1000000",
    "-1234567.891", "0.000001", "123456789012345",
)

private fun numberSerialization(locale: Locale): List<String> = buildList {
    for (text in NUMBER_VALUES) {
        val value = Decimal.parse(text)
        add(CldrNumber.format(value, locale))
        add(CldrNumber.format(value, locale, notation = NumberNotation.COMPACT_SHORT))
        add(CldrNumber.format(value, locale, notation = NumberNotation.COMPACT_LONG))
        add(CldrNumber.format(value, locale, minimumFractionDigits = 2, maximumFractionDigits = 2))
    }
}

private fun currencySerialization(locale: Locale): List<String> = buildList {
    for (code in listOf("USD", "EUR", "JPY", "BHD", "CHF", "HUF", "CLP")) {
        val currency = Currency.forCodeOrNull(code) ?: continue
        for (minorUnits in listOf(0L, 1L, -1L, 123456L, -123456L, 999999999L)) {
            add(CldrCurrency.format(CurrencyAmount(currency, minorUnits), locale))
        }
    }
}

private fun pluralSerialization(locale: Locale): List<String> = buildList {
    for (text in NUMBER_VALUES) {
        val value = Decimal.parse(text)
        add(CldrNumberPlurals.pluralCategory(value, value.scale, locale, PluralType.CARDINAL).cldrName)
    }
}

/**
 * Compares the digests this JVM produces against the committed fixture, or
 * rewrites the fixture when `updateDigests` asked for that.
 */
private fun settleDigests(domain: String, tags: List<String>, serialize: (String) -> List<String>) {
    // The ledger's generator run shares this source set; stand aside for it.
    if (Ledger.writing) return

    val digests = tags.associateWith { Digest.of(serialize(it)) }
    val file = digestFile(domain)

    if (Ledger.writingDigests) {
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                appendLine("// GENERATED by ./gradlew :conformance-icu:updateDigests. Do not edit.")
                appendLine("//")
                appendLine("// One FNV-1a digest per locale of what this library answers, taken on the")
                appendLine("// JVM. The other targets are held to it, which is how a Regex, a Double or")
                appendLine("// a case mapping behaving differently on one platform gets caught without")
                appendLine("// a golden wide enough to be unlinkable.")
                appendLine("//")
                appendLine("// Not an oracle: correctness is :conformance-icu's job. This says only")
                appendLine("// that every target computes the same thing.")
                appendLine("package dev.carcara.kotlinx.locale.conformance")
                appendLine()
                appendLine("public val ${domain.digestValName()}: Map<String, String> = mapOf(")
                for ((tag, digest) in digests) appendLine("    \"$tag\" to \"$digest\",")
                appendLine(")")
            },
        )
        return
    }

    assertTrue(
        file.isFile,
        "$domain has no committed digests at ${file.path}. " +
            "Run ./gradlew :conformance-icu:updateDigests.",
    )
    val committed = Regex(""""([^"]+)" to "([0-9a-f]{8})"""")
        .findAll(file.readText())
        .associate { it.groupValues[1] to it.groupValues[2] }

    val moved = digests.filter { (tag, digest) -> committed[tag] != null && committed[tag] != digest }
    val missing = digests.keys - committed.keys

    assertTrue(
        moved.isEmpty() && missing.isEmpty(),
        "$domain digests are stale: ${moved.size} locales answer differently than the committed " +
            "fixture and ${missing.size} are missing from it.\n" +
            moved.entries.take(10).joinToString("\n") { (tag, digest) ->
                "    $tag: committed ${committed[tag]}, now $digest"
            } +
            "\nIf the change was intended, run ./gradlew :conformance-icu:updateDigests and review the diff.",
    )
}

private fun String.digestValName(): String =
    split('-').mapIndexed { i, part -> if (i == 0) part else part.replaceFirstChar(Char::uppercase) }
        .joinToString("") + "Digests"

/** Each domain's digests live in the `commonTest` of the module that owns it. */
private fun digestFile(domain: String): File {
    val root = Ledger.rootDir()
    val module = when (domain) {
        "number", "plural" -> "kotlinx-locale-number-cldr-full"
        "currency-format" -> "kotlinx-locale-currency-cldr-full"
        else -> error("no module owns the '$domain' digests")
    }
    val pkg = when (domain) {
        "number", "plural" -> "number/conformance"
        "currency-format" -> "currency/conformance"
        else -> error("no package owns the '$domain' digests")
    }
    return root.resolve("$module/src/commonTest/kotlin/dev/carcara/kotlinx/locale/$pkg")
        .resolve("${domain.digestValName().replaceFirstChar(Char::uppercase)}Data.kt")
}
