package dev.carcara.kotlinx.locale.size

import dev.carcara.kotlinx.locale.codegen.kotlinUnescape
import dev.carcara.kotlinx.locale.codegen.pipeline.PayloadSize

/**
 * The marker every generated source opens with, and the only thing that decides
 * whether a file counts.
 *
 * Reading the header rather than matching a path means a table that moves
 * modules keeps being measured, and a hand-written file that happens to sit in
 * the same directory never starts being measured.
 */
public const val GENERATED_MARKER: String = "// GENERATED by :codegen"

/**
 * Every string literal a generated source declares, however it is spelled.
 *
 * `UNIX_LINES`, because Java treats U+2028 and U+2029 as line terminators and
 * the fifteen-bit packing emits characters throughout U+0800 to U+FFFF. Without
 * it a literal containing one is silently skipped, and eighty-one of them are.
 *
 * The alternation is what catches the tables that are not `internal val`: a
 * codec's shared tables ride in a `put(CODEC_TABLES_KEY, "...")`, and a few
 * hand-placed tables are `public val`. Matching only the common spelling left a
 * quarter of a megabyte of shipped data out of the report.
 */
private val LITERAL = Regex(
    // Possessive quantifiers throughout. The obvious `(?:[^"\\]|\\.)*` nests a
    // quantifier inside an alternation, and on a literal of a million characters
    // that recurses deep enough to overflow the stack rather than to backtrack.
    """(?:^(?:internal|public) (?:actual )?(?:const )?val \w+: String =\s*+\n?+\s*+|put\([^,\n]++, )"([^"\\]*+(?:\\.[^"\\]*+)*+)"""",
    setOf(RegexOption.MULTILINE, RegexOption.UNIX_LINES),
)

/**
 * What one generated table costs.
 *
 * [family] groups the per-locale files a table is bucketed into, so the report
 * reads as one row per table rather than one per file.
 */
public class DataTable(public val module: String, public val family: String, public val constants: Int, public val size: PayloadSize) {

    override fun toString(): String = "$module/$family: $constants constants, $size"

    public companion object
}

/**
 * Reads what a checkout's generated sources weigh.
 *
 * Deliberately measures the decoded value rather than the source text: a
 * `` is six characters of Kotlin and one character of artifact, and only
 * the second reaches a binary. That is what [kotlinUnescape] is for.
 */
public object GeneratedData {

    /** commonMain plus the packing each platform family compiles. */
    public val PLATFORMS: Map<String, Set<String>> = mapOf(
        "Android, JVM" to setOf("commonMain", "utf8Main", "utf8DeflatedMain"),
        "Kotlin/JS, Wasm" to setOf("commonMain", "utf8Main", "utf8PlainMain"),
        "Kotlin/Native" to setOf("commonMain", "utf16Main"),
    )

    /** Everything, which double counts a packed table and is only for finding files. */
    public val ALL_SOURCE_SETS: Set<String> =
        PLATFORMS.values.flatten().toSet()

    /**
     * Every generated file in [sources], keyed by its path relative to the root.
     *
     * Taking the contents as a map rather than reading the disk directly is what
     * lets the same code measure a git ref, which has no directory to walk.
     */
    public fun tablesOf(sources: Map<String, String>, sourceSets: Set<String> = ALL_SOURCE_SETS): List<DataTable> {
        val byFamily = LinkedHashMap<Pair<String, String>, MutableList<String>>()
        for ((path, text) in sources) {
            if (GENERATED_MARKER !in text) continue
            val parts = path.split('/')
            // A target compiles commonMain plus exactly one packed source set,
            // so a caller asking what a platform pays passes that one. Adding
            // them all would count the same records in three different packings
            // and report a number nobody is charged.
            if (parts.size > 2 && parts[1] == "src" && parts[2] !in sourceSets) continue
            val module = parts.first()
            val family = familyOf(path.substringAfterLast('/').removeSuffix(".kt"))
            for (match in LITERAL.findAll(text)) {
                byFamily.getOrPut(module to family) { ArrayList() } += kotlinUnescape(match.groupValues[1])
            }
        }
        return byFamily
            .map { (key, values) -> DataTable(key.first, key.second, values.size, PayloadSize.of(values)) }
            .sortedWith(compareBy({ it.module }, { it.family }))
    }

    /**
     * `CurrencyNames_a` and `CurrencyNames_b` are one table; `Country` is
     * another. The suffix is a bucket the emitter chose, not a fact worth
     * reporting on its own.
     */
    private fun familyOf(fileName: String): String {
        val underscore = fileName.lastIndexOf('_')
        if (underscore <= 0) return fileName
        val suffix = fileName.substring(underscore + 1)
        val bucketed = suffix.length <= 3 && suffix.all { it.isLetterOrDigit() } && suffix.none { it.isUpperCase() }
        return if (bucketed) fileName.substring(0, underscore) else fileName
    }
}
