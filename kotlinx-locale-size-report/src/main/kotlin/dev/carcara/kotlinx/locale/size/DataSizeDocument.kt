package dev.carcara.kotlinx.locale.size

import dev.carcara.kotlinx.locale.codegen.pipeline.PayloadSize

/** Renders the measurements as the document that ships in `docs/`. */
public object DataSizeDocument {

    private fun kb(bytes: Long): String = String.format("%,.1f KB", bytes / 1024.0)

    /** The unit a platform family is charged in. */
    private fun unit(platform: String): (PayloadSize) -> Long = when (platform) {
        "Kotlin/Native" -> PayloadSize::utf16
        "Android, JVM" -> PayloadSize::mutf8
        else -> PayloadSize::utf8
    }

    public fun render(byPlatform: Map<String, List<DataTable>>): String = buildString {
        appendLine("# Generated data size")
        appendLine()
        appendLine("Generated by `./gradlew updateDataSizeDoc`. Do not edit.")
        appendLine()
        appendLine("What the generated tables weigh, in the unit each platform charges for a")
        appendLine("string. These are the characters that reach an artifact, not the source")
        appendLine("text that spells them: a `\\u001F` is six characters of Kotlin and one")
        appendLine("character of data.")
        appendLine()
        appendLine("| platform | stores a literal as | cost per character |")
        appendLine("| --- | --- | --- |")
        appendLine("| Android, JVM | modified UTF-8 | 1 byte under U+0080, 2 under U+0800, 3 above |")
        appendLine("| Kotlin/JS, Wasm | UTF-8 | the same |")
        appendLine("| Kotlin/Native | UTF-16 | 2 bytes, every character alike |")
        appendLine()
        appendLine("Each column counts `commonMain` plus the one packed source set that")
        appendLine("platform compiles, so a table packed three ways is counted once per")
        appendLine("column rather than three times in each. There is no compressed column:")
        appendLine("whether a bundle is gzipped in transit is the consumer's build talking,")
        appendLine("and `docs/size.md` measures that end for Kotlin/JS.")
        appendLine()

        val platforms = byPlatform.keys.toList()

        appendLine("## By module")
        appendLine()
        appendLine("| module | " + platforms.joinToString(" | ") + " |")
        appendLine("| --- |" + platforms.joinToString("") { " ---: |" })
        val modules = byPlatform.values.flatten().map(DataTable::module).distinct()
        val totals = platforms.associateWith { 0L }.toMutableMap()
        for (module in modules.sortedByDescending { module ->
            byPlatform.values.first().filter { it.module == module }.sumOf { it.size.utf8 }
        }) {
            append("| ").append(module)
            for (platform in platforms) {
                val size = byPlatform.getValue(platform)
                    .filter { it.module == module }
                    .fold(PayloadSize.Zero) { total, row -> total + row.size }
                val bytes = unit(platform)(size)
                totals[platform] = totals.getValue(platform) + bytes
                append(" | ").append(kb(bytes))
            }
            appendLine(" |")
        }
        append("| **total**")
        for (platform in platforms) append(" | **").append(kb(totals.getValue(platform))).append("**")
        appendLine(" |")
        appendLine()

        appendLine("## By table")
        appendLine()
        appendLine("| module | table | constants | " + platforms.joinToString(" | ") + " |")
        appendLine("| --- | --- | ---: |" + platforms.joinToString("") { " ---: |" })
        val reference = byPlatform.getValue(platforms.first())
        for (row in reference.sortedByDescending { it.size.utf8 }) {
            append("| ").append(row.module).append(" | ").append(row.family)
            append(" | ").append(row.constants)
            for (platform in platforms) {
                val match = byPlatform.getValue(platform)
                    .firstOrNull { it.module == row.module && it.family == row.family }
                append(" | ").append(match?.let { kb(unit(platform)(it.size)) } ?: "0.0 KB")
            }
            appendLine(" |")
        }
    }

    /** The before-and-after table, which is what a codec is judged on. */
    public fun renderComparison(reference: String, before: List<DataTable>, after: List<DataTable>): String = buildString {
        val was = before.associateBy { it.module to it.family }
        val now = after.associateBy { it.module to it.family }
        val keys = (was.keys + now.keys).sortedWith(compareBy({ it.first }, { it.second }))

        appendLine("Generated data size against $reference")
        appendLine()
        appendLine("%-38s %-24s %14s %14s %14s".format("module", "table", "UTF-8", "modified UTF-8", "UTF-16"))
        var changed = 0
        for (key in keys) {
            val a = was[key]?.size ?: PayloadSize.Zero
            val b = now[key]?.size ?: PayloadSize.Zero
            if (a.utf8 == b.utf8 && a.mutf8 == b.mutf8 && a.utf16 == b.utf16) continue
            changed++
            appendLine(
                "%-38s %-24s %14s %14s %14s".format(
                    key.first,
                    key.second,
                    delta(a.utf8, b.utf8),
                    delta(a.mutf8, b.mutf8),
                    delta(a.utf16, b.utf16),
                ),
            )
        }
        if (changed == 0) appendLine("  no table changed size")
        appendLine()

        val a = before.fold(PayloadSize.Zero) { acc, row -> acc + row.size }
        val b = after.fold(PayloadSize.Zero) { acc, row -> acc + row.size }
        appendLine(
            "%-63s %14s %14s %14s".format(
                "TOTAL",
                delta(a.utf8, b.utf8),
                delta(a.mutf8, b.mutf8),
                delta(a.utf16, b.utf16),
            ),
        )
        appendLine()
        appendLine("%-63s %14s %14s %14s".format("  before", kb(a.utf8), kb(a.mutf8), kb(a.utf16)))
        appendLine("%-63s %14s %14s %14s".format("  after", kb(b.utf8), kb(b.mutf8), kb(b.utf16)))
    }

    private fun delta(before: Long, after: Long): String {
        if (before == after) return "="
        val percent = if (before == 0L) 0.0 else (after - before) * 100.0 / before
        return String.format("%+,.1f KB %+.1f%%", (after - before) / 1024.0, percent)
    }
}
