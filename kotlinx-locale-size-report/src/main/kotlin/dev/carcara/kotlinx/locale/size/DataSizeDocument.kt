package dev.carcara.kotlinx.locale.size

import dev.carcara.kotlinx.locale.codegen.pipeline.PayloadSize

/** Renders the measurements as the document that ships in `docs/`. */
public object DataSizeDocument {

    private fun kb(bytes: Long): String = String.format("%,.1f KB", bytes / 1024.0)

    public fun render(tables: List<DataTable>): String = buildString {
        appendLine("# Generated data size")
        appendLine()
        appendLine("Generated by `./gradlew updateDataSizeDoc`. Do not edit.")
        appendLine()
        appendLine("What the generated tables weigh, in the unit each platform charges for a")
        appendLine("string. These are the characters that reach an artifact, not the source")
        appendLine("text that spells them: a `\\u001F` is six characters of Kotlin and one")
        appendLine("character of data.")
        appendLine()
        appendLine("| unit | who pays it |")
        appendLine("| --- | --- |")
        appendLine("| UTF-8 | the Kotlin/JS bundle, and whatever compresses it |")
        appendLine("| modified UTF-8 | the JVM class-file constant pool and the Android dex string pool |")
        appendLine("| UTF-16 | Kotlin/Native, which stores every literal as UTF-16 whatever the characters are |")
        appendLine()
        appendLine("There is no compressed column. Whether a bundle is gzipped, brotlied or")
        appendLine("shipped raw is the consumer's build pipeline talking, and `docs/size.md`")
        appendLine("already measures that end of it for Kotlin/JS. This document measures the")
        appendLine("data, which is the half a codec changes.")
        appendLine()

        appendLine("## By module")
        appendLine()
        appendLine("| module | tables | constants | UTF-8 | modified UTF-8 | UTF-16 |")
        appendLine("| --- | ---: | ---: | ---: | ---: | ---: |")
        val byModule = tables.groupBy(DataTable::module)
        for ((module, rows) in byModule.entries.sortedByDescending { entry -> entry.value.sumOf { it.size.utf16 } }) {
            val size = rows.fold(PayloadSize.Zero) { total, row -> total + row.size }
            appendLine(
                "| $module | ${rows.size} | ${rows.sumOf { it.constants }} | " +
                    "${kb(size.utf8)} | ${kb(size.mutf8)} | ${kb(size.utf16)} |",
            )
        }
        val total = tables.fold(PayloadSize.Zero) { acc, row -> acc + row.size }
        appendLine(
            "| **total** | **${tables.size}** | **${tables.sumOf { it.constants }}** | " +
                "**${kb(total.utf8)}** | **${kb(total.mutf8)}** | **${kb(total.utf16)}** |",
        )
        appendLine()

        appendLine("## By table")
        appendLine()
        appendLine("| module | table | constants | UTF-8 | modified UTF-8 | UTF-16 |")
        appendLine("| --- | --- | ---: | ---: | ---: | ---: |")
        for (row in tables.sortedByDescending { it.size.utf16 }) {
            appendLine(
                "| ${row.module} | ${row.family} | ${row.constants} | " +
                    "${kb(row.size.utf8)} | ${kb(row.size.mutf8)} | ${kb(row.size.utf16)} |",
            )
        }
    }

    /** The before-and-after table, which is what a codec is judged on. */
    public fun renderComparison(reference: String, before: List<DataTable>, after: List<DataTable>): String = buildString {
        val was = before.associateBy { it.module to it.family }
        val now = after.associateBy { it.module to it.family }
        val keys = (was.keys + now.keys).sortedWith(compareBy({ it.first }, { it.second }))

        appendLine("Generated data size against $reference")
        appendLine()
        appendLine(
            "%-38s %-24s %14s %14s %14s".format("module", "table", "UTF-8", "modified UTF-8", "UTF-16"),
        )
        var changed = 0
        for (key in keys) {
            val a = was[key]?.size ?: PayloadSize.Zero
            val b = now[key]?.size ?: PayloadSize.Zero
            if (a.utf8 == b.utf8 && a.mutf8 == b.mutf8 && a.utf16 == b.utf16) continue
            changed++
            appendLine(
                "%-38s %-24s %14s %14s %14s".format(
                    key.first,
                    key.second,
                    delta(a.utf8, b.utf8),
                    delta(a.mutf8, b.mutf8),
                    delta(a.utf16, b.utf16),
                ),
            )
        }
        if (changed == 0) appendLine("  no table changed size")
        appendLine()

        val a = before.fold(PayloadSize.Zero) { acc, row -> acc + row.size }
        val b = after.fold(PayloadSize.Zero) { acc, row -> acc + row.size }
        appendLine(
            "%-63s %14s %14s %14s".format("TOTAL", delta(a.utf8, b.utf8), delta(a.mutf8, b.mutf8), delta(a.utf16, b.utf16)),
        )
        appendLine()
        appendLine("%-63s %14s %14s %14s".format("  before", kb(a.utf8), kb(a.mutf8), kb(a.utf16)))
        appendLine("%-63s %14s %14s %14s".format("  after", kb(b.utf8), kb(b.mutf8), kb(b.utf16)))
    }

    private fun delta(before: Long, after: Long): String {
        if (before == after) return "="
        val percent = if (before == 0L) 0.0 else (after - before) * 100.0 / before
        return String.format("%+,.1f KB %+.1f%%", (after - before) / 1024.0, percent)
    }
}
