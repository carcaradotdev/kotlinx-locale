package dev.carcara.kotlinx.locale.codegen

import java.io.File

/**
 * The phone metadata tables and the object that reads them.
 *
 * Emitted one constant per territory rather than one per table, for a reason
 * that is not stylistic: a JVM string constant is capped at 65535 bytes and the
 * territory table is 116 kilobytes. Splitting by territory is also the split a
 * reader would want, because it is the unit the data is about, and it groups the
 * output into files small enough to open.
 */
public fun emitPhoneTables(outputRoot: File, registryPackage: String, source: String, territories: String, formats: String) {
    writeRegistry(
        outputRoot,
        registryPackage,
        source,
        table = territories,
        filePrefix = "PhoneTerritories",
        constPrefix = "PHONE_TERRITORY",
        registryName = "phoneTerritoryRegistry",
        doc = "Every territory's numbering plan: its calling code, its prefixes and its number descriptions.",
    )
    writeRegistry(
        outputRoot,
        registryPackage,
        source,
        table = formats,
        filePrefix = "PhoneFormats",
        constPrefix = "PHONE_FORMAT",
        registryName = "phoneFormatRegistry",
        doc = "Every territory's number formats, which only formatting reads.",
    )
}

private fun writeRegistry(
    outputRoot: File,
    registryPackage: String,
    source: String,
    table: String,
    filePrefix: String,
    constPrefix: String,
    registryName: String,
    doc: String,
) {
    val dir = outputRoot.resolve(registryPackage.replace('.', '/')).apply { mkdirs() }
    dir.listFiles { f: File -> f.name.startsWith(filePrefix) && f.extension == "kt" }?.forEach(File::delete)

    val header = "// GENERATED by :codegen from $source. Do not edit.\n" +
        "// Regenerate with: ./gradlew :codegen:generateLocaleData\n" +
        "package $registryPackage\n"

    val entries = table.split(LIST_SEPARATOR).filter(String::isNotEmpty)
    val byId = entries.associateBy { it.substringBefore(FIELD_SEPARATOR) }

    // Bucketed by first letter, the way the skeleton goldens are: 254 constants
    // in one file is a file no one opens twice.
    val buckets = byId.keys.groupBy { it.first() }
    for ((bucket, ids) in buckets) {
        dir.resolve("${filePrefix}_$bucket.kt").writeText(
            buildString {
                append(header)
                for (id in ids.sorted()) {
                    append("\ninternal val ${constPrefix}_${id.uppercase()}: String =\n    \"")
                    append(kotlinEscape(byId.getValue(id)))
                    append("\"\n")
                }
            },
        )
    }

    dir.resolve("$filePrefix.kt").writeText(
        buildString {
            append(header)
            append("\n/** $doc */\n")
            append("internal val $registryName: Map<String, String> = buildMap(${byId.size}) {\n")
            for (id in byId.keys.sorted()) {
                append("    put(\"${kotlinEscape(id)}\", ${constPrefix}_${id.uppercase()})\n")
            }
            append("}\n")
        },
    )
    println("[codegen] emitted ${byId.size} $registryName entries to $dir")
}

/** The `PhoneNumbers`-shaped binding: the source object plus what a consumer calls. */
public fun emitPhoneBinding(outputRoot: File, spec: BindingSpec, hasFormats: Boolean) {
    val file = outputRoot.packageFile(spec.packageName, "PhoneNumbers.kt")
    val formats = if (hasFormats) "phoneFormatRegistry" else "emptyMap()"
    val imports = buildList {
        addAll(
            listOf(
                "dev.carcara.kotlinx.locale.InternalKotlinxLocaleApi",
                "dev.carcara.kotlinx.locale.country.Country",
                "dev.carcara.kotlinx.locale.phone.PhoneNumber",
                "dev.carcara.kotlinx.locale.phone.PhoneNumberFormat",
                "dev.carcara.kotlinx.locale.phone.PhoneNumberSource",
                "dev.carcara.kotlinx.locale.phone.PhoneParseResult",
                "dev.carcara.kotlinx.locale.phone.metadata.runtime.PayloadPhoneNumbers",
                "${spec.registryPackage}.phoneTerritoryRegistry",
            ),
        )
        if (hasFormats) add("${spec.registryPackage}.phoneFormatRegistry")
    }

    file.writeText(
        preamble(spec, imports, "@file:OptIn(InternalKotlinxLocaleApi::class)") + """
        |
        |/**
        | * Phone number parsing, validation and formatting over the bundled metadata.
        | *
        | * Not keyed by locale: a number is valid or it is not, and it formats the way
        | * its own territory formats it, whoever is reading. That is why this object
        | * takes a [Country] where the rest of the library takes a
        | * [dev.carcara.kotlinx.locale.Locale].
        | */
        |public object ${spec.objectName} : PhoneNumberSource by PayloadPhoneNumbers(
        |    phoneTerritoryRegistry,
        |    $formats,
        |)
        |
        |/** [this] read as a phone number for [region], or `null`. */
        |public fun String.toPhoneNumberOrNull(region: Country? = null): PhoneNumber? =
        |    (${spec.objectName}.parse(this, region) as? PhoneParseResult.Parsed)?.number
        |
        |/** True when [this] is a number that could exist in [region]. */
        |public fun String.isValidPhoneNumber(region: Country? = null): Boolean =
        |    toPhoneNumberOrNull(region)?.let(${spec.objectName}::isValid) == true
        |
        |/** This number written in [format]. */
        |public fun PhoneNumber.format(format: PhoneNumberFormat = PhoneNumberFormat.INTERNATIONAL): String =
        |    ${spec.objectName}.format(this, format)
        |
        |/** True when this number could exist in its territory. */
        |public fun PhoneNumber.isValid(): Boolean = ${spec.objectName}.isValid(this)
        |
        |/** The territory this number belongs to, or `null` when its calling code is not geographic. */
        |public fun PhoneNumber.region(): Country? = ${spec.objectName}.regionOf(this)
        |
        """.trimMargin(),
    )
    println("[codegen] emitted ${spec.objectName} to $file")
}
