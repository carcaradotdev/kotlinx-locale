package dev.carcara.kotlinx.locale.codegen

import java.io.File

/**
 * Emits the tender windows as one packed string rather than as enum constructor
 * arguments.
 *
 * Constructor arguments are retained by every consumer of the enum and no
 * dead-code eliminator can drop them, so three more of them would be paid for by
 * a build that only ever calls `Currency.forCode("USD")`. An unreferenced string
 * constant can be dropped, and where it cannot it is still one allocation rather
 * than three fields on three hundred entries.
 *
 * One row per ordinal, so the decode is an index rather than a lookup.
 */
public fun emitCurrencyTender(outputFile: File, cldrTag: String, isoPublished: String, currencies: List<CurrencyEntry>) {
    outputFile.parentFile.mkdirs()
    val rows = currencies.joinToString(";") { currency ->
        "${currency.tenderFrom},${currency.tenderTo},${if (currency.isTender) 1 else 0},${if (currency.isCurrent) 1 else 0}"
    }
    outputFile.writeText(
        """
        |// GENERATED by :codegen from ISO 4217 lists one and three ($isoPublished) and CLDR $cldrTag. Do not edit.
        |// Regenerate with: ./gradlew :codegen:generateLocaleData
        |package dev.carcara.kotlinx.locale.currency.internal
        |
        |import dev.carcara.kotlinx.locale.InternalKotlinxLocaleApi
        |
        |/**
        | * `from,to,tender,current` per Currency ordinal, joined by `;`.
        | *
        | * The days are proleptic Gregorian day numbers, with Int.MIN_VALUE and
        | * Int.MAX_VALUE for an unbounded end. Decoded lazily by
        | * `kotlinx-locale-currency-core`, which is where the extensions that read it
        | * live.
        | */
        |@InternalKotlinxLocaleApi
        |public val currencyTenderTable: String =
        |    "${kotlinEscape(rows)}"
        |
        """.trimMargin(),
    )
    println("[codegen] emitted tender windows for ${currencies.size} currencies to $outputFile")
}
