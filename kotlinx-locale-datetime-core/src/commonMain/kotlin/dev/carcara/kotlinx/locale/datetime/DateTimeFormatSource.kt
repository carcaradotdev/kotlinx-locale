package dev.carcara.kotlinx.locale.datetime

import dev.carcara.kotlinx.locale.Locale
import dev.carcara.kotlinx.locale.LocaleDataSource
import kotlinx.datetime.DayOfWeek
import kotlinx.datetime.LocalDate
import kotlinx.datetime.LocalDateTime
import kotlinx.datetime.LocalTime
import kotlinx.datetime.Month
import kotlinx.datetime.isoDayNumber
import kotlinx.datetime.number

/** The four CLDR standard format lengths. */
public enum class FormatStyle {
    FULL,
    LONG,
    MEDIUM,
    SHORT,
    ;

    public companion object
}

/** Width of localized month and day-of-week names. */
public enum class TextStyle {
    FULL,
    ABBREVIATED,
    NARROW,
    ;

    public companion object
}

/**
 * A source that renders dates, times and calendar names in a locale's
 * conventions.
 *
 * The interface is shaped around the operation rather than around the tables
 * CLDR stores, because the platforms cannot supply the tables: `Intl` does not
 * hand out CLDR patterns and `NSDateFormatter` derives patterns from templates
 * rather than exposing the localized standard ones. Both can format, so
 * formatting is what the contract asks for.
 *
 * Months are numbered 1 to 12 and days of week 1 (Monday) to 7, matching
 * `Month.number` and `DayOfWeek.isoDayNumber`.
 */
public interface DateTimeFormatSource : LocaleDataSource {

    public fun formatDateOrNull(date: LocalDate, style: FormatStyle, locale: Locale): String?

    public fun formatTimeOrNull(time: LocalTime, style: FormatStyle, locale: Locale): String?

    public fun formatDateTimeOrNull(dateTime: LocalDateTime, dateStyle: FormatStyle, timeStyle: FormatStyle, locale: Locale): String?

    public fun monthNameOrNull(month: Int, style: TextStyle, locale: Locale): String?

    /**
     * The month name in [context], or `null` when this source has none.
     *
     * Defaulted to the format names, which is what a source with no stand-alone
     * table should answer and what CLDR root's own alias says for every locale
     * that declares no stand-alone form of its own. Defaulted rather than
     * abstract so that adding the axis breaks no implementor.
     */
    public fun monthNameOrNull(month: Int, style: TextStyle, context: NameContext, locale: Locale): String? =
        monthNameOrNull(month, style, locale)

    public fun dayOfWeekNameOrNull(isoDayNumber: Int, style: TextStyle, locale: Locale): String?

    /** The weekday name in [context]; see [monthNameOrNull]. */
    public fun dayOfWeekNameOrNull(isoDayNumber: Int, style: TextStyle, context: NameContext, locale: Locale): String? =
        dayOfWeekNameOrNull(isoDayNumber, style, locale)

    public companion object
}

/**
 * [date] written for [locale].
 *
 * Unlike country and currency, a date has no code to degrade to, so a source
 * with nothing for this locale falls back to ISO 8601. That is close to what
 * CLDR root produces today (`2026-07-27` at SHORT), and a source generated by
 * the Gradle plugin never reaches it because the plugin requires a fallback
 * locale.
 */
public fun DateTimeFormatSource.format(date: LocalDate, style: FormatStyle, locale: Locale): String =
    formatDateOrNull(date, style, locale) ?: date.toString()

/** [time] written for [locale]; falls back to ISO 8601. */
public fun DateTimeFormatSource.format(time: LocalTime, style: FormatStyle, locale: Locale): String =
    formatTimeOrNull(time, style, locale) ?: time.toString()

/** [dateTime] written for [locale]; falls back to ISO 8601. */
public fun DateTimeFormatSource.format(dateTime: LocalDateTime, dateStyle: FormatStyle, timeStyle: FormatStyle, locale: Locale): String =
    formatDateTimeOrNull(dateTime, dateStyle, timeStyle, locale) ?: dateTime.toString()

/** The name of [month] in [locale] and [context]; falls back to the English enum name. */
public fun DateTimeFormatSource.displayName(month: Month, style: TextStyle, context: NameContext, locale: Locale): String =
    monthNameOrNull(month.number, style, context, locale) ?: month.name

/** The name of [dayOfWeek] in [locale] and [context]; falls back to the English enum name. */
public fun DateTimeFormatSource.displayName(dayOfWeek: DayOfWeek, style: TextStyle, context: NameContext, locale: Locale): String =
    dayOfWeekNameOrNull(dayOfWeek.isoDayNumber, style, context, locale) ?: dayOfWeek.name

/** The name of [month] in [locale]; falls back to the English enum name. */
public fun DateTimeFormatSource.displayName(month: Month, style: TextStyle, locale: Locale): String =
    monthNameOrNull(month.number, style, locale) ?: month.name

/** The name of [dayOfWeek] in [locale]; falls back to the English enum name. */
public fun DateTimeFormatSource.displayName(dayOfWeek: DayOfWeek, style: TextStyle, locale: Locale): String =
    dayOfWeekNameOrNull(dayOfWeek.isoDayNumber, style, locale) ?: dayOfWeek.name

/** Answers from [primary], and from [fallback] wherever primary has nothing. */
public class FallbackDateTimeFormats(private val primary: DateTimeFormatSource, private val fallback: DateTimeFormatSource) :
    DateTimeFormatSource {

    override val supportedLocales: Set<Locale>
        get() = primary.supportedLocales + fallback.supportedLocales

    override fun formatDateOrNull(date: LocalDate, style: FormatStyle, locale: Locale): String? =
        primary.formatDateOrNull(date, style, locale) ?: fallback.formatDateOrNull(date, style, locale)

    override fun formatTimeOrNull(time: LocalTime, style: FormatStyle, locale: Locale): String? =
        primary.formatTimeOrNull(time, style, locale) ?: fallback.formatTimeOrNull(time, style, locale)

    override fun formatDateTimeOrNull(dateTime: LocalDateTime, dateStyle: FormatStyle, timeStyle: FormatStyle, locale: Locale): String? =
        primary.formatDateTimeOrNull(dateTime, dateStyle, timeStyle, locale)
            ?: fallback.formatDateTimeOrNull(dateTime, dateStyle, timeStyle, locale)

    override fun monthNameOrNull(month: Int, style: TextStyle, locale: Locale): String? =
        primary.monthNameOrNull(month, style, locale) ?: fallback.monthNameOrNull(month, style, locale)

    override fun monthNameOrNull(month: Int, style: TextStyle, context: NameContext, locale: Locale): String? =
        primary.monthNameOrNull(month, style, context, locale) ?: fallback.monthNameOrNull(month, style, context, locale)

    override fun dayOfWeekNameOrNull(isoDayNumber: Int, style: TextStyle, context: NameContext, locale: Locale): String? =
        primary.dayOfWeekNameOrNull(isoDayNumber, style, context, locale)
            ?: fallback.dayOfWeekNameOrNull(isoDayNumber, style, context, locale)

    override fun dayOfWeekNameOrNull(isoDayNumber: Int, style: TextStyle, locale: Locale): String? =
        primary.dayOfWeekNameOrNull(isoDayNumber, style, locale)
            ?: fallback.dayOfWeekNameOrNull(isoDayNumber, style, locale)

    public companion object
}
